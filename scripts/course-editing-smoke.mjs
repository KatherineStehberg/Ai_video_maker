import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { chromium } from '../.tmp/browser-tools/node_modules/playwright-core/index.mjs';
fs.mkdirSync(path.resolve('.tmp'), { recursive: true });
const scratch=fs.mkdtempSync(path.resolve('.tmp/course-browser-'));
process.env.COURSE_PRODUCTION_ENABLED='0';
process.env.AIVM_PROJECTS_DIR=path.join(scratch,'projects');
process.env.AIVM_OUTPUT_DIR=path.join(scratch,'output');
process.env.AIVM_JOBS_DIR=path.join(scratch,'jobs');
process.env.AIVM_COURSE_QUEUE_DIR=path.join(scratch,'queue');
const {createServer}=await import('../src/server.js');
const {loadPack}=await import('../src/course-production/index.js');
const server=createServer();await new Promise(r=>server.listen(0,'127.0.0.1',r));
const isolated='http://127.0.0.1:'+server.address().port;
const live=process.env.AIVM_BROWSER_BASE || 'http://127.0.0.1:4321';
const browser=await chromium.launch({executablePath:process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const item=loadPack().items.find(i=>i.id==='RPM-2026-001');
const report={};
async function openFirst(base){
 await page.goto(base+'/course-production.html');
 await page.waitForFunction(()=>document.querySelectorAll('#items section').length===15);
 assert.match(await page.locator('#environment').innerText(),/pausada/);
 const card=page.locator('#items section').filter({hasText:item.title});
 assert.equal(await card.getByRole('link',{name:'Ver video',exact:true}).count(),0);
 await card.getByRole('link',{name:'Editar proyecto',exact:true}).or(card.getByRole('button',{name:'Editar proyecto',exact:true})).click();
 await page.waitForURL(/project-editor.html\?id=/);
 await page.waitForFunction(()=>document.querySelector('#titulo').value.length>0);
 assert.equal(await page.locator('#titulo').inputValue(),item.title);
 return new URL(page.url()).searchParams.get('id');
}
try {
 const liveId=await openFirst(live);report.liveUrl=live+'/project-editor.html?id='+liveId;
 const liveData=await (await page.request.get(live+'/api/project-editor/projects/'+liveId)).json();
 assert.deepEqual(liveData.derivado.escenas.map(s=>s.text),item.scenes.map(s=>s.text));
 assert.deepEqual(liveData.proyecto.outputs,{});
 const id=await openFirst(isolated);
 const narration=item.scenes[0].text+' Persistence check.';
 await page.locator('#panel-cuerpo textarea').first().fill(narration);
 await page.locator('#panel-cuerpo input[type=number]').first().fill('42');
 await page.locator('#panel-cuerpo input[type=number]').first().dispatchEvent('change');
 await page.locator('[data-herr=subtitulos]').click();
 await page.locator('#panel-cuerpo input[type=color]').first().fill('#ffcc00');
 await page.locator('#panel-cuerpo input[type=color]').first().dispatchEvent('change');
 await page.locator('[data-herr=recursos]').click();
 assert.equal(await page.locator('#panel-cuerpo input[type=file]').count(),1);
 await page.locator('#panel-cuerpo input[type=text]').first().fill('User resource search');
 await page.locator('#guardar').click();
 await page.waitForFunction(()=>document.querySelector('#estado-guardado').textContent==='Guardado');
 await page.reload();
 await page.waitForFunction(()=>document.querySelector('#titulo').value.length>0);
 assert.equal(await page.locator('#panel-cuerpo textarea').first().inputValue(),narration);
 assert.equal(await page.locator('#panel-cuerpo input[type=number]').first().inputValue(),'42');
 await page.locator('[data-herr=subtitulos]').click();
 assert.equal(await page.locator('#panel-cuerpo input[type=color]').first().inputValue(),'#ffcc00');
 await page.locator('[data-herr=recursos]').click();
 assert.equal(await page.locator('#panel-cuerpo input[type=text]').first().inputValue(),'User resource search');
 const data=await (await page.request.get(isolated+'/api/project-editor/projects/'+id)).json();
 assert.ok(data.derivado.escenas.every(s=>!s.recurso.path));
 await page.screenshot({path:path.join(scratch,'editor.png'),fullPage:true});
 const state=await (await page.request.get(live+'/api/course-production')).json();
 assert.equal(state.productionEnabled,false);assert.ok(state.entries.every(e=>e.status==='pending'&&!e.videoUrl));
 assert.equal(state.entries.filter(e=>e.projectId).length,1);
 assert.deepEqual(errors,[]);
 report.sceneCount=item.scenes.length;report.persistence='narration, duration, captions and resource search saved and reopened';report.errors=errors;
 fs.writeFileSync(path.join(scratch,'result.json'),JSON.stringify(report,null,2));console.log(JSON.stringify(report,null,2));
} finally {await browser.close();await new Promise(r=>server.close(r));}
