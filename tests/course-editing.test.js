import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';

fs.mkdirSync(path.resolve('.tmp'), { recursive: true });
const root = fs.mkdtempSync(path.resolve('.tmp/course-editing-'));
process.env.COURSE_PRODUCTION_ENABLED = '0';
process.env.AIVM_PROJECTS_DIR = path.join(root, 'projects');
process.env.AIVM_COURSE_QUEUE_DIR = path.join(root, 'queue');
process.env.AIVM_JOBS_DIR = path.join(root, 'jobs');
process.env.AIVM_OUTPUT_DIR = path.join(root, 'output');
const { createServer } = await import('../src/server.js');
const { loadPack } = await import('../src/course-production/index.js');
const { loadProject, saveProject, listProjects, projectFile } = await import('../src/core/project.js');
const { prepareCourseProject } = await import('../src/course-production/editing.js');

test('paused courses prepare only the requested draft, reuse edits and persist without rendering', async t => {
 const server=createServer(); await new Promise(r=>server.listen(0,'127.0.0.1',r));
 t.after(()=>new Promise(r=>server.close(r)));
 const base='http://127.0.0.1:'+server.address().port;
 const pack=loadPack(), item=pack.items.find(i=>i.id==='RPM-2026-001');
 const get=async route=>{const r=await fetch(base+route);assert.equal(r.status,200);return r.json();};
 const initial=await get('/api/course-production');
 assert.equal(initial.productionEnabled,false);assert.equal(typeof initial.environment.ok,'boolean');
 assert.ok(initial.entries.every(e=>e.status==='pending'&&!e.videoUrl));assert.equal(listProjects().length,0);
 const route='/api/course-production/projects/'+item.id;
 assert.equal((await fetch(base+route,{method:'POST'})).status,403);
 assert.equal((await fetch(base+route,{method:'POST',headers:{'x-course-request':'1',origin:'https://example.com'}})).status,403);
 const response=await fetch(base+route,{method:'POST',headers:{'x-course-request':'1'}});
 assert.equal(response.status,200);const prepared=await response.json();
 let p=loadProject(prepared.projectId);
 assert.equal(p.script,item.script);assert.deepEqual(p.scenes.map(s=>s.text),item.scenes.map(s=>s.text));
 assert.equal(p.status,'draft');assert.deepEqual(p.outputs,{});assert.ok(p.scenes.every(s=>!s.assetPath&&!s.narrationPath));
 const before=await get('/api/project-editor/projects/'+p.id), first=p.scenes[0];
 const update=await fetch(base+'/api/project-editor/projects/'+p.id,{method:'PATCH',headers:{'content-type':'application/json','x-editor-request':'1'},body:JSON.stringify({revision:before.derivado.revision,voice:{enabled:false},captions:{style:{color:'#ffcc00'}},scenes:[{id:first.id,text:first.text+' Local editing check.',caption:'Custom caption',visualPrompt:'User search reference',duration:42,assetPath:null}]})});
 assert.equal(update.status,200);
 const reopened=await get('/api/project-editor/projects/'+p.id);
 assert.equal(reopened.proyecto.voice.enabled,false);assert.equal(reopened.proyecto.captions.style.color,'#ffcc00');
 p=loadProject(p.id);assert.equal(p.scenes[0].caption,'Custom caption');assert.equal(p.scenes[0].visualPrompt,'User search reference');assert.equal(p.scenes[0].duration,42);
 const bytes=fs.readFileSync(projectFile(p.id),'utf8');
 const repeated=await fetch(base+route,{method:'POST',headers:{'x-course-request':'1'}});assert.equal(repeated.status,200);assert.equal((await repeated.json()).projectId,p.id);
 assert.equal(prepareCourseProject(pack,item.id).id,p.id);assert.equal(fs.readFileSync(projectFile(p.id),'utf8'),bytes);
 const state=await get('/api/course-production'), entry=state.entries.find(e=>e.id===item.id);
 assert.equal(entry.editUrl,prepared.editUrl);assert.equal(entry.status,'pending');assert.equal(entry.videoUrl,null);
 assert.equal(listProjects().length,1);assert.ok(state.entries.slice(1).every(e=>!e.projectId));
 assert.throws(()=>prepareCourseProject(pack,item.id,{projectId:'vid_missing'}),/no existe/);
 p.metadata={...p.metadata,courseRenderProof:{ok:true,fullyDecoded:true,audio:true,motionVerified:true}};saveProject(p);
 const stale=await get('/api/course-production');const legacy=stale.entries.find(e=>e.id===item.id);assert.equal(legacy.status,'timing_review');assert.equal(legacy.videoUrl,null);assert.ok(legacy.editUrl);
 const next=pack.items[1], collision=projectFile('vid_course_'+next.id);fs.writeFileSync(collision,'not a project');
 assert.throws(()=>prepareCourseProject(pack,next.id),/no se sobrescribe/);assert.equal(fs.readFileSync(collision,'utf8'),'not a project');
 const stateFile=path.join(process.env.AIVM_COURSE_QUEUE_DIR,'state.json');const saved=JSON.parse(fs.readFileSync(stateFile));
 assert.ok(Object.values(saved.entries).every(e=>e.status==='pending'&&!e.jobId));
});
